-- 040: cấp mã tự động cho danh mục/sản phẩm/nguyên liệu/bàn/khu vực/khuyến mãi.
-- Chạy qua tools/database/Apply-Migration.ps1 -Version 40.
-- Chỉ phụ thuộc object của baseline và sp_CapMa ở 001/020 nên gate theo schema 038.
SET NOCOUNT ON;
SET XACT_ABORT ON;
IF @@TRANCOUNT=0 OR NOT EXISTS(SELECT 1 FROM dbo.SchemaMigrations WHERE Version=38)
    THROW 52207,N'Migration 038 bắt buộc.',1;
IF OBJECT_ID(N'dbo.sp_CapMa',N'P') IS NULL
 OR COL_LENGTH(N'dbo.KHUYENMAI',N'MaKM') IS NULL OR COL_LENGTH(N'dbo.NGUYENVATLIEU',N'MaNVL') IS NULL
    THROW 52207,N'Thiếu object danh mục/sp_CapMa; cần đối chiếu trước nâng cấp.',1;

DECLARE @ncc BIGINT,@pt BIGINT,@dt BIGINT,@tc BIGINT,@cv BIGINT,@ca BIGINT,
        @sp BIGINT,@nvl BIGINT,@ban BIGINT,@kv BIGINT,@km BIGINT;
SELECT @ncc=COALESCE(MAX(TRY_CONVERT(BIGINT,SUBSTRING(MaNCC,4,2))),0)+1 FROM dbo.NHACUNGCAP WITH(TABLOCKX,HOLDLOCK)
 WHERE MaNCC COLLATE Latin1_General_100_BIN2 LIKE 'NCC[0-9][0-9]';
SELECT @pt=COALESCE(MAX(TRY_CONVERT(BIGINT,SUBSTRING(MaPT,3,3))),0)+1 FROM dbo.PHUONGTHUCTT WITH(TABLOCKX,HOLDLOCK)
 WHERE MaPT COLLATE Latin1_General_100_BIN2 LIKE 'PT[0-9][0-9][0-9]';
SELECT @dt=COALESCE(MAX(TRY_CONVERT(BIGINT,SUBSTRING(MaDT,3,3))),0)+1 FROM dbo.DOITACGIAOHANG WITH(TABLOCKX,HOLDLOCK)
 WHERE MaDT COLLATE Latin1_General_100_BIN2 LIKE 'DT[0-9][0-9][0-9]';
SELECT @tc=COALESCE(MAX(TRY_CONVERT(BIGINT,SUBSTRING(MaDMTC,3,3))),0)+1 FROM dbo.DANHMUC_THUCHI WITH(TABLOCKX,HOLDLOCK)
 WHERE MaDMTC COLLATE Latin1_General_100_BIN2 LIKE 'TC[0-9][0-9][0-9]';
SELECT @cv=COALESCE(MAX(TRY_CONVERT(BIGINT,SUBSTRING(MaCV,3,3))),0)+1 FROM dbo.CHUCVU WITH(TABLOCKX,HOLDLOCK)
 WHERE MaCV COLLATE Latin1_General_100_BIN2 LIKE 'CV[0-9][0-9][0-9]';
SELECT @ca=COALESCE(MAX(TRY_CONVERT(BIGINT,SUBSTRING(MaCa,3,3))),0)+1 FROM dbo.CALAMVIEC WITH(TABLOCKX,HOLDLOCK)
 WHERE MaCa COLLATE Latin1_General_100_BIN2 LIKE 'CA[0-9][0-9][0-9]';
SELECT @sp=COALESCE(MAX(TRY_CONVERT(BIGINT,SUBSTRING(MaSP,3,3))),0)+1 FROM dbo.SANPHAM WITH(TABLOCKX,HOLDLOCK)
 WHERE MaSP COLLATE Latin1_General_100_BIN2 LIKE 'SP[0-9][0-9][0-9]';
SELECT @nvl=COALESCE(MAX(TRY_CONVERT(BIGINT,SUBSTRING(MaNVL,4,2))),0)+1 FROM dbo.NGUYENVATLIEU WITH(TABLOCKX,HOLDLOCK)
 WHERE MaNVL COLLATE Latin1_General_100_BIN2 LIKE 'NVL[0-9][0-9]';
SELECT @ban=COALESCE(MAX(TRY_CONVERT(BIGINT,SUBSTRING(MaBan,2,4))),0)+1 FROM dbo.BAN WITH(TABLOCKX,HOLDLOCK)
 WHERE MaBan COLLATE Latin1_General_100_BIN2 LIKE 'B[0-9][0-9][0-9][0-9]';
SELECT @kv=COALESCE(MAX(TRY_CONVERT(BIGINT,SUBSTRING(MaKV,3,3))),0)+1 FROM dbo.KHUVUC WITH(TABLOCKX,HOLDLOCK)
 WHERE MaKV COLLATE Latin1_General_100_BIN2 LIKE 'KV[0-9][0-9][0-9]';
SELECT @km=COALESCE(MAX(TRY_CONVERT(BIGINT,SUBSTRING(MaKM,3,8))),0)+1 FROM dbo.KHUYENMAI WITH(TABLOCKX,HOLDLOCK)
 WHERE MaKM COLLATE Latin1_General_100_BIN2 LIKE 'KM[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]';
IF @ncc>99 OR @nvl>99 OR @pt>999 OR @dt>999 OR @tc>999 OR @cv>999 OR @ca>999
 OR @sp>999 OR @ban>9999 OR @kv>999 OR @km>99999999
    THROW 51302,N'Dải mã hiện có đã vượt giới hạn; cần rà soát trước khi tạo sequence.',1;

DECLARE @sql NVARCHAR(MAX)=
 N'CREATE SEQUENCE dbo.SeqNhaCungCap AS BIGINT START WITH '+CONVERT(NVARCHAR(20),@ncc)+N' INCREMENT BY 1 MINVALUE 1 MAXVALUE 99 NO CYCLE NO CACHE;'
+N'CREATE SEQUENCE dbo.SeqPhuongThuc AS BIGINT START WITH '+CONVERT(NVARCHAR(20),@pt)+N' INCREMENT BY 1 MINVALUE 1 MAXVALUE 999 NO CYCLE NO CACHE;'
+N'CREATE SEQUENCE dbo.SeqDoiTac AS BIGINT START WITH '+CONVERT(NVARCHAR(20),@dt)+N' INCREMENT BY 1 MINVALUE 1 MAXVALUE 999 NO CYCLE NO CACHE;'
+N'CREATE SEQUENCE dbo.SeqLoaiThuChi AS BIGINT START WITH '+CONVERT(NVARCHAR(20),@tc)+N' INCREMENT BY 1 MINVALUE 1 MAXVALUE 999 NO CYCLE NO CACHE;'
+N'CREATE SEQUENCE dbo.SeqChucVu AS BIGINT START WITH '+CONVERT(NVARCHAR(20),@cv)+N' INCREMENT BY 1 MINVALUE 1 MAXVALUE 999 NO CYCLE NO CACHE;'
+N'CREATE SEQUENCE dbo.SeqCaLam AS BIGINT START WITH '+CONVERT(NVARCHAR(20),@ca)+N' INCREMENT BY 1 MINVALUE 1 MAXVALUE 999 NO CYCLE NO CACHE;'
+N'CREATE SEQUENCE dbo.SeqSanPham AS BIGINT START WITH '+CONVERT(NVARCHAR(20),@sp)+N' INCREMENT BY 1 MINVALUE 1 MAXVALUE 999 NO CYCLE NO CACHE;'
+N'CREATE SEQUENCE dbo.SeqNguyenVatLieu AS BIGINT START WITH '+CONVERT(NVARCHAR(20),@nvl)+N' INCREMENT BY 1 MINVALUE 1 MAXVALUE 99 NO CYCLE NO CACHE;'
+N'CREATE SEQUENCE dbo.SeqBan AS BIGINT START WITH '+CONVERT(NVARCHAR(20),@ban)+N' INCREMENT BY 1 MINVALUE 1 MAXVALUE 9999 NO CYCLE NO CACHE;'
+N'CREATE SEQUENCE dbo.SeqKhuVuc AS BIGINT START WITH '+CONVERT(NVARCHAR(20),@kv)+N' INCREMENT BY 1 MINVALUE 1 MAXVALUE 999 NO CYCLE NO CACHE;'
+N'CREATE SEQUENCE dbo.SeqKhuyenMai AS BIGINT START WITH '+CONVERT(NVARCHAR(20),@km)+N' INCREMENT BY 1 MINVALUE 1 MAXVALUE 99999999 NO CYCLE NO CACHE;';
EXEC sys.sp_executesql @sql;
GO
ALTER PROCEDURE dbo.sp_CapMa @Loai VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @number BIGINT;
    BEGIN TRY
        IF @Loai='HOADON'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqHoaDon;
            SELECT @Loai AS Loai,CAST('HD'+RIGHT('00000000'+CONVERT(VARCHAR(20),@number),8) AS CHAR(10)) AS Ma;
        END
        ELSE IF @Loai='DANHMUC_SP'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqDanhMuc;
            SELECT @Loai AS Loai,CAST('DM'+RIGHT('000'+CONVERT(VARCHAR(20),@number),3) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='NHANVIEN'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqNhanVien;
            SELECT @Loai AS Loai,CAST('NV'+RIGHT('000'+CONVERT(VARCHAR(20),@number),3) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='PHIEUTHUCHI'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqPhieuThuChi;
            SELECT @Loai AS Loai,CAST('TC'+RIGHT('00000000'+CONVERT(VARCHAR(20),@number),8) AS CHAR(10)) AS Ma;
        END
        ELSE IF @Loai='PHIEUNHAP'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqPhieuNhap;
            SELECT @Loai AS Loai,CAST('PN'+RIGHT('00000000'+CONVERT(VARCHAR(20),@number),8) AS CHAR(10)) AS Ma;
        END
        ELSE IF @Loai='CONGNO_NCC'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqCongNo;
            SELECT @Loai AS Loai,CAST('CN'+RIGHT('00000000'+CONVERT(VARCHAR(20),@number),8) AS CHAR(10)) AS Ma;
        END
        ELSE IF @Loai='PHIEUXUAT'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqPhieuXuat;
            SELECT @Loai AS Loai,CAST('PX'+RIGHT('00000000'+CONVERT(VARCHAR(20),@number),8) AS CHAR(10)) AS Ma;
        END
        ELSE IF @Loai='PHIEUKIEMKE'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqKiemKe;
            SELECT @Loai AS Loai,CAST('KK'+RIGHT('00000000'+CONVERT(VARCHAR(20),@number),8) AS CHAR(10)) AS Ma;
        END
        ELSE IF @Loai='NHACUNGCAP'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqNhaCungCap;
            SELECT @Loai AS Loai,CAST('NCC'+RIGHT('00'+CONVERT(VARCHAR(20),@number),2) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='PHUONGTHUCTT'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqPhuongThuc;
            WHILE @number=10 SET @number=NEXT VALUE FOR dbo.SeqPhuongThuc;
            SELECT @Loai AS Loai,CAST('PT'+RIGHT('000'+CONVERT(VARCHAR(20),@number),3) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='DOITACGIAOHANG'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqDoiTac;
            SELECT @Loai AS Loai,CAST('DT'+RIGHT('000'+CONVERT(VARCHAR(20),@number),3) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='DANHMUC_THUCHI'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqLoaiThuChi;
            WHILE @number IN (5,11,12) SET @number=NEXT VALUE FOR dbo.SeqLoaiThuChi;
            SELECT @Loai AS Loai,CAST('TC'+RIGHT('000'+CONVERT(VARCHAR(20),@number),3) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='CHUCVU'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqChucVu;
            SELECT @Loai AS Loai,CAST('CV'+RIGHT('000'+CONVERT(VARCHAR(20),@number),3) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='CALAMVIEC'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqCaLam;
            SELECT @Loai AS Loai,CAST('CA'+RIGHT('000'+CONVERT(VARCHAR(20),@number),3) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='SANPHAM'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqSanPham;
            SELECT @Loai AS Loai,CAST('SP'+RIGHT('000'+CONVERT(VARCHAR(20),@number),3) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='NGUYENVATLIEU'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqNguyenVatLieu;
            SELECT @Loai AS Loai,CAST('NVL'+RIGHT('00'+CONVERT(VARCHAR(20),@number),2) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='BAN'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqBan;
            SELECT @Loai AS Loai,CAST('B'+RIGHT('0000'+CONVERT(VARCHAR(20),@number),4) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='KHUVUC'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqKhuVuc;
            SELECT @Loai AS Loai,CAST('KV'+RIGHT('000'+CONVERT(VARCHAR(20),@number),3) AS CHAR(5)) AS Ma;
        END
        ELSE IF @Loai='KHUYENMAI'
        BEGIN
            SET @number=NEXT VALUE FOR dbo.SeqKhuyenMai;
            SELECT @Loai AS Loai,CAST('KM'+RIGHT('00000000'+CONVERT(VARCHAR(20),@number),8) AS CHAR(10)) AS Ma;
        END
        ELSE THROW 51301,'Unsupported code source.',1;
    END TRY
    BEGIN CATCH
        IF ERROR_NUMBER()=11728 THROW 51302,'Code range exhausted; contact administrator.',1;
        THROW;
    END CATCH
END;
GO
